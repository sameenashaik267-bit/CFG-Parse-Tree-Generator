# ---------------- AMBIGUOUS CFG ----------------

GRAMMAR_TEXT = """
E -> E PLUS E | E MINUS E | E TIMES E | E DIVIDE E | E POWER E
E -> LPAREN E RPAREN | PLUS E | MINUS E | NUMBER | ID
PLUS -> '+'
MINUS -> '-'
TIMES -> '*'
DIVIDE -> '/'
POWER -> '^'
LPAREN -> '('
RPAREN -> ')'
NUMBER -> 'NUM'
ID -> 'VAR'
"""

grammar = CFG.fromstring(GRAMMAR_TEXT)
parser = ChartParser(grammar)

# ---------------- TOKENIZER ----------------

TOKEN_PATTERN = re.compile(
    r"\s*(?:(\d+(?:\.\d*)?|\.\d+)|"
    r"([A-Za-z_][A-Za-z_0-9]*)|"
    r"([+\-*/^()]))"
)

OPERATOR_MAP = {
    "+": "+",
    "-": "-",
    "*": "*",
    "/": "/",
    "^": "^",
    "(": "(",
    ")": ")"
}


def tokenize_expression(expression):
    """Convert input into CFG tokens and preserve original tokens."""

    if not expression.strip():
        raise ValueError("Please enter an expression.")

    grammar_tokens = []
    original_tokens = []
    pos = 0

    while pos < len(expression):
        if expression[pos:].strip() == "":
            break

        match = TOKEN_PATTERN.match(expression, pos)

        if not match:
            raise ValueError(
                f"Unexpected character near: {expression[pos:pos+12]}"
            )

        number, identifier, operator = match.groups()

        if number is not None:
            grammar_tokens.append("NUM")
            original_tokens.append(number)

        elif identifier is not None:
            grammar_tokens.append("VAR")
            original_tokens.append(identifier)

        else:
            grammar_tokens.append(OPERATOR_MAP[operator])
            original_tokens.append(operator)

        pos = match.end()

    return grammar_tokens, original_tokens


# ---------------- RESTORE ORIGINAL TOKENS ----------------

def restore_original_tokens(tree, original_tokens):
    """Replace generic NUM and VAR leaves with original input tokens."""

    tree = tree.copy(deep=True)
    leaf_positions = tree.treepositions("leaves")

    if len(leaf_positions) != len(original_tokens):
        raise ValueError("Could not match tree leaves to the input.")

    for position, original in zip(leaf_positions, original_tokens):
        tree[position] = original

    return tree


# ---------------- CLEAN PARSE TREE VISUALIZATION ----------------

def draw_parse_tree(tree, title):
    """Draw a readable tree with balanced spacing and clear labels."""

    positions = {}
    edges = []
    leaf_counter = [0]

    def layout(node, path=(), level=0):
        if isinstance(node, Tree):
            child_positions = []

            for index, child in enumerate(node):
                child_path = path + (index,)
                child_x = layout(child, child_path, level + 1)
                child_positions.append(child_x)
                edges.append((path, child_path))

            x = sum(child_positions) / len(child_positions)
            positions[path] = (x, level, node.label())
            return x

        x = leaf_counter[0]
        leaf_counter[0] += 1
        positions[path] = (x, level, str(node))
        return x

    layout(tree)

    leaf_count = max(leaf_counter[0], 1)
    depth = tree.height()

    # Increase the figure width for expressions with many tokens.
    fig_width = max(8, leaf_count * 1.25)
    fig_height = max(4, depth * 0.9)

    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    fig.patch.set_facecolor("#F4F8F0")
    ax.set_facecolor("#F4F8F0")

    # Draw connecting lines first so they remain behind the nodes.
    for parent_path, child_path in edges:
        px, py, _ = positions[parent_path]
        cx, cy, _ = positions[child_path]

        ax.plot(
            [px, cx],
            [-py - 0.13, -cy + 0.13],
            color="#91AE91",
            linewidth=1.4,
            zorder=1
        )

    # Draw all grammar nodes and terminal symbols.
    for path, (x, level, label) in positions.items():
        is_nonterminal = isinstance(
            tree[path] if path else tree, Tree
        )

        if is_nonterminal:
            facecolor = "#DCEBDD"
            edgecolor = "#64866A"
            fontweight = "bold"
        else:
            facecolor = "#F7F4DE"
            edgecolor = "#A3B18A"
            fontweight = "normal"

        ax.text(
            x,
            -level,
            label,
            ha="center",
            va="center",
            fontsize=10,
            fontweight=fontweight,
            color="#294936",
            bbox={
                "boxstyle": "round,pad=0.4",
                "facecolor": facecolor,
                "edgecolor": edgecolor,
                "linewidth": 1.2
            },
            zorder=2
        )

    ax.set_title(
        title,
        fontsize=15,
        fontweight="bold",
        color="#355740",
        pad=18
    )

    ax.set_xlim(-0.7, max(leaf_count - 0.3, 0.7))
    ax.set_ylim(-depth - 0.7, 0.8)
    ax.axis("off")

    fig.tight_layout()
    return fig


